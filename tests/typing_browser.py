"""Real Chromium typing + deterministic browser clock. No screenshot assertions."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright
BASE=os.environ.get('LAB_URL','http://127.0.0.1:8786/').rstrip('/')+'/typing/'
checks=[]
def check(name, value):
    if not value:
        print('FAIL STATE:', page.locator('#status').inner_text(), page.locator('#result').inner_text(), page.locator('#remaining').inner_text(), page.locator('#storageStatus').inner_text(), errors)
    assert value, name
    checks.append(name)
with sync_playwright() as pw:
    chrome=next((Path.home()/'.cache/ms-playwright').glob('*/chrome-linux64/chrome'))
    browser=pw.chromium.launch(executable_path=str(chrome),args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1200,'height':900})
    page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.clock.install();page.goto(BASE)
    check('three scene selector',page.locator('#scene option').count()==3)
    field=page.locator('#entry')
    def start(scene='supply',mode='words',seconds='30'):
        page.locator('#scene').select_option(scene);page.locator('#mode').select_option(mode);page.locator('#duration').select_option(seconds);page.locator('#start').click()
    def type_target():
        field.press_sequentially(page.locator('#target').get_attribute('data-text'))
    start()
    check('paste cannot start timer',page.evaluate("""() => {const e=new InputEvent('beforeinput',{inputType:'insertFromPaste',data:'cat',cancelable:true,bubbles:true});document.querySelector('#entry').dispatchEvent(e);return e.defaultPrevented;}"""))
    page.clock.fast_forward(10000)
    check('first input starts timer',page.locator('#remaining').inner_text()=='30')
    field.press('x');check('wrong is editable',page.locator('#target .wrong').count()==1)
    field.press('Backspace');type_target()
    check('supply loads crate',page.locator('.crate').count()==1 and page.locator('#completed').inner_text()=='1')
    check('auto advance no separator',field.input_value()=='')
    check('paste drop beforeinput prevented',page.evaluate("""() => ['paste','drop','beforeinput'].every(t=>{const e=t==='beforeinput'?new InputEvent(t,{inputType:'insertFromPaste',bubbles:true,cancelable:true}):new Event(t,{bubbles:true,cancelable:true});document.querySelector('#entry').dispatchEvent(e);return e.defaultPrevented;})"""))
    page.clock.fast_forward(31000)
    check('ends and score once',field.is_disabled() and page.locator('#scores tbody tr').count()==1)
    check('corrected typo accuracy 75', '75%' in page.locator('#result').inner_text())
    c=next(c for c in context.cookies() if c['name']=='lucas_lab_typing_v1')
    check('real bounded path cookie',c['path'].endswith('/typing/') and c['sameSite']=='Lax' and len(c['value'])<3800)
    page.reload();check('reload persistence',page.locator('#scores tbody tr').count()==1)
    start();field.press('c');page.locator('#scene').select_option('bridge')
    check('switch abandons incomplete',page.locator('#scores tbody tr').count()==0)
    start('bridge','python');type_target()
    check('bridge segment robot movement',page.locator('.bridge-segment').count()==1 and page.locator('#robot').get_attribute('data-step')=='1')
    page.clock.fast_forward(31000);check('python score board',page.locator('#scores tbody tr').count()==1)
    start('bridge','symbols','60');type_target()
    check('expression internal spaces complete',page.locator('#completed').inner_text()=='1' and field.input_value()=='')
    page.clock.fast_forward(61000);check('60s expression board',page.locator('#scores tbody tr').count()==1)
    start('defense','words','60');field.press('x')
    check('wrong no laser',page.locator('#laser').count()==0)
    field.press('Backspace');type_target()
    check('visible turret interception',page.locator('#laser').count()==1 and page.locator('#completed').inner_text()=='1')
    page.clock.run_for(20000)
    check('miss damages shield',int(page.locator('#shield').inner_text())<3)
    page.clock.run_for(25000)
    check('zero shield explicit failure','防御失败' in page.locator('#result').inner_text() and page.locator('#shield').inner_text()=='0' and field.is_disabled())
    saved=next(c['value'] for c in context.cookies() if c['name']=='lucas_lab_typing_v1')
    page.clock.fast_forward(20000)
    check('failure saves exactly once',next(c['value'] for c in context.cookies() if c['name']=='lucas_lab_typing_v1')==saved)
    page.locator('#restart').click();check('defense reset shield',page.locator('#shield').inner_text()=='3')
    field.press('c');page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))")
    check('hidden pauses explicit unranked',page.locator('#resume').is_visible() and field.is_disabled())
    remaining=page.locator('#remaining').inner_text();page.clock.fast_forward(90000)
    check('pause frozen',page.locator('#remaining').inner_text()==remaining)
    page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>false})")
    page.locator('#resume').click();page.clock.run_for(65000)
    check('paused round no farming score',next(c['value'] for c in context.cookies() if c['name']=='lucas_lab_typing_v1')==saved and '不入榜' in page.locator('#result').inner_text())
    page.once('dialog',lambda d:d.dismiss());page.locator('#clear').click();check('cancel clear keeps',len(context.cookies())>0)
    page.once('dialog',lambda d:d.accept());page.locator('#clear').click();page.reload()
    check('clear persists',page.locator('#scores tbody tr').count()==0)
    for width in [320,360]:
        page.set_viewport_size({'width':width,'height':800})
        for scene in ['supply','defense','bridge']:
            page.locator('#scene').select_option(scene)
            check(f'mobile {width} {scene}',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    for scene in ['supply','defense','bridge']:
        for mode in ['words','python','symbols']:
            start(scene,mode);type_target()
            check(f'keyboard complete {scene} {mode}',page.locator('#completed').inner_text()=='1')
    page.set_viewport_size({'width':320,'height':800})
    start('defense','symbols','60')
    for n in range(9):
        check(f'falling expression fits {n}',page.evaluate("""() => {const a=document.querySelector('#arena').getBoundingClientRect();return [...document.querySelectorAll('.enemy')].every(e=>{const r=e.getBoundingClientRect();return r.left>=a.left&&r.right<=a.right;});}"""))
        type_target();page.clock.run_for(5500)
    start('supply','symbols')
    page.evaluate("""() => {const e=document.querySelector('#entry');e.dispatchEvent(new CompositionEvent('compositionstart'));e.value='x =';e.dispatchEvent(new InputEvent('input',{isComposing:true,data:'x ='}));}""")
    page.clock.run_for(300)
    check('composition draft survives rendering',field.input_value()=='x =')
    page.evaluate("document.querySelector('#entry').dispatchEvent(new CompositionEvent('compositionend'))")
    field.press(' ');field.press('1')
    check('composition expression counts once',page.locator('#completed').inner_text()=='1')
    page.clock.fast_forward(31000)
    check('composition accurate','100%' in page.locator('#result').inner_text())
    start('supply');field.press('c');page.clock.set_system_time(page.evaluate('Date.now()+35000'));page.evaluate("window.dispatchEvent(new Event('focus'))")
    check('missed callback deadline truthful',field.is_disabled())
    blocked=browser.new_context();bp=blocked.new_page();bp.add_init_script("Object.defineProperty(document,'cookie',{get(){return ''},set(v){}})");bp.goto(BASE)
    check('cookie blocked warning','无法' in bp.locator('#storageStatus').inner_text())
    secure=browser.new_context();origin=BASE.rsplit('/typing/',1)[0]+'/'
    secure.route('https://typing.example/lucas-lab/**',lambda r:r.fulfill(response=r.fetch(url=origin+r.request.url.split('/lucas-lab/',1)[1])))
    sp=secure.new_page();sp.goto('https://typing.example/lucas-lab/typing/')
    sc=next(c for c in secure.cookies() if c['name']=='lucas_lab_typing_v1')
    check('HTTPS Secure prefix',sc['secure'] and sc['path']=='/lucas-lab/typing/')
    check('no JS errors',not errors)
    browser.close()
print(f'{len(checks)} browser checks passed: '+', '.join(checks))
