"""V3 actual-keyboard browser acceptance; clock advances, never injected scores."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright
BASE=os.environ.get('LAB_URL','http://127.0.0.1:8786/').rstrip('/')+'/typing/'
checks=[]
def check(name,value):
    assert value,name
    checks.append(name)
with sync_playwright() as pw:
    chrome=next((Path.home()/'.cache/ms-playwright').glob('*/chrome-linux64/chrome'))
    browser=pw.chromium.launch(executable_path=str(chrome),args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':1100})
    context.add_init_script("window.spoken=[]; window.SpeechSynthesisUtterance=class {constructor(text){this.text=text}}; Object.defineProperty(window,'speechSynthesis',{value:{speak(u){window.spoken.push(u.text)},cancel(){},getVoices(){return []}}});")
    page=context.new_page();errors=[];page.on('pageerror',lambda e: errors.append(str(e)))
    page.clock.install();page.goto(BASE)
    check('missing device voice warning','英语语音' in page.locator('#audioStatus').inner_text())
    check('illustrated mission chooser',page.locator('[data-mission]').count()==3 and page.locator('#chooser').is_visible())
    out=Path('verification');out.mkdir(exist_ok=True)
    page.screenshot(path=str(out/'typing-v3-chooser.png'),full_page=True)
    field=page.locator('#entry')
    def start(scene='supply',speed='20',mode='words'):
        if page.locator('#back').is_visible(): page.locator('#back').click()
        page.locator('#mode').select_option(mode);page.locator('#speed').fill(speed);page.locator('#speed').dispatch_event('input')
        page.locator(f'[data-mission="{scene}"]').click()
    def target(): return page.locator('#target').get_attribute('data-text')
    def type_target(): field.press_sequentially(target())
    start();check('mission launches',page.locator('#play').is_visible())
    arena=page.locator('#arena');arena.evaluate('(e)=>e.dataset.identity="persistent"')
    original=target();field.press('~');field.press('Backspace');field.press('Delete');field.press('ArrowLeft')
    check('immutable wrong slot',field.input_value()=='~' and page.locator('#target .wrong').count()==1)
    field.press('ControlOrMeta+a');field.press('z');check('selection cannot replace',field.input_value()==('~z' if len(original)>2 else ''))
    while field.input_value(): field.press('~')
    check('failed full attempt no cargo',page.locator('#completed').inner_text()=='0' and target()==original)
    type_target();check('arm cargo success',page.locator('#completed').inner_text()=='1' and page.locator('.arm.loading').count()==1 and page.locator('.cargo-loaded').count()==1)
    check('word labels stay above transient cargo',page.locator('.vehicle.active').evaluate('(e)=>Number(getComputedStyle(e).zIndex)')>page.locator('.cargo-flight').evaluate('(e)=>Number(getComputedStyle(e).zIndex)'))
    check('persistent arena',arena.get_attribute('data-identity')=='persistent')
    check('speech only on active changes',len(page.evaluate('window.spoken'))>=2)
    page.screenshot(path=str(out/'typing-v3-supply.png'),full_page=True)
    check('forbidden browser insert types',page.evaluate("""()=>['insertFromPaste','insertFromDrop','insertReplacementText','historyUndo','historyRedo','deleteContentBackward'].every(inputType=>{const e=new InputEvent('beforeinput',{inputType,data:'x',cancelable:true,bubbles:true});document.querySelector('#entry').dispatchEvent(e);return e.defaultPrevented})"""))
    page.clock.fast_forward(61000);check('finished once real score',field.is_disabled() and page.locator('#scores tbody tr').count()==1)
    cookie=next(c for c in context.cookies() if c['name']=='lucas_lab_typing_v1')
    check('bounded local path cookie',len(cookie['value'])<3800 and cookie['path'].endswith('/typing/') and cookie['sameSite']=='Lax')
    saved=cookie['value'];page.clock.fast_forward(10000);check('one save',next(c['value'] for c in context.cookies() if c['name']=='lucas_lab_typing_v1')==saved)
    page.reload();start();check('reload real score',page.locator('#scores tbody tr').count()==1)
    start('defense','60');type_target();check('laser interception',page.locator('.laser-effect').count()==1)
    for _ in range(2):type_target()
    check('sentence formation ships',page.locator('.vehicle.formation').count()>=3)
    while page.locator('.vehicle.formation').count():type_target()
    check('perfect formation bonus','编队' in page.locator('#status').inner_text())
    page.screenshot(path=str(out/'typing-v3-defense.png'),full_page=True)
    page.clock.run_for(59000);check('shield failure','防御失败' in page.locator('#result').inner_text())
    start('assault','20');type_target();check('missile damages boss',page.locator('.missile-effect').count()==1 and int(page.locator('#bossHP').inner_text())<100)
    for _ in range(4):type_target()
    check('boss defeated wave advances',int(page.locator('#wave').inner_text())>=2)
    page.screenshot(path=str(out/'typing-v3-assault.png'),full_page=True)
    check('audio switches',page.locator('#music').is_visible() and page.locator('#effects').is_visible() and page.locator('#speech').is_visible())
    page.locator('#music').check();page.locator('#effects').uncheck();page.locator('#speech').uncheck()
    start('supply','5','symbols');check('speed settings fair','5 WPM' in page.locator('#groupLabel').inner_text())
    field.press('x');page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))")
    check('background unranked pause',page.locator('#resume').is_visible() and field.is_disabled())
    remaining=page.locator('#remaining').inner_text();page.clock.fast_forward(90000);check('pause frozen',page.locator('#remaining').inner_text()==remaining)
    page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>false})");page.locator('#resume').click();page.clock.fast_forward(61000)
    check('unranked no save','不入榜' in page.locator('#result').inner_text())
    for width in [320,390,1440]:
        page.set_viewport_size({'width':width,'height':1000})
        for scene in ['supply','defense','assault']:
            start(scene,'20','symbols');type_target();page.clock.run_for(800)
            check(f'no overflow {width} {scene}',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
            check('mobile status single-line labels',page.locator('#bossBox').evaluate('(e)=>getComputedStyle(e).whiteSpace')=='nowrap' if width<400 else True)
            check(f'attached labels fit {width} {scene}',page.evaluate("""()=>{const a=document.querySelector('#arena').getBoundingClientRect();return [...document.querySelectorAll('.vehicle')].every(e=>{const r=e.getBoundingClientRect();return r.left>=a.left-1&&r.right<=a.right+1})}"""))
        if width<400:page.screenshot(path=str(out/f'typing-v3-mobile-{width}.png'),full_page=True)
    blocked=browser.new_context();bp=blocked.new_page();bp.add_init_script("Object.defineProperty(document,'cookie',{get(){return ''},set(v){}})");bp.goto(BASE)
    check('cookie blocked graceful','无法' in bp.locator('#storageStatus').inner_text())
    for moving_scene in ['supply','defense','assault']:
        start(moving_scene);field.press('~')
        before=page.locator('.vehicle').first.evaluate('(e)=>e.style.transform')
        page.clock.run_for(1200)
        check(moving_scene+' visible target moves across frames',page.locator('.vehicle').first.evaluate('(e)=>e.style.transform')!=before)
    start('supply','20','python');type_target();check('Python actual keyboard',page.locator('#completed').inner_text()=='1')
    field.press('x');draft=field.input_value()
    page.evaluate("""()=>{const e=document.querySelector('#entry');e.dispatchEvent(new CompositionEvent('compositionstart'));e.value='中文';e.dispatchEvent(new InputEvent('input',{isComposing:true,data:'中文'}));e.dispatchEvent(new CompositionEvent('compositionend'));}""")
    check('IME never silently inserts composition',field.input_value()==draft and '英文输入法' in page.locator('#status').inner_text())
    start('supply');page.emulate_media(reduced_motion='reduce');field.press('~');before=page.locator('.vehicle').first.evaluate('(e)=>e.style.transform');page.clock.run_for(1200)
    check('reduced motion retains gameplay travel',page.locator('.vehicle').first.evaluate('(e)=>e.style.transform')!=before)
    page.emulate_media(reduced_motion='no-preference')
    page.clock.set_system_time(page.evaluate('Date.now()+65000'));page.evaluate("window.dispatchEvent(new Event('focus'))")
    check('deadline catches missed callbacks',field.is_disabled())
    page.locator('#back').click();page.locator('#duration').select_option('30');start('assault');type_target();page.clock.fast_forward(31000)
    check('30-second exact deadline',field.is_disabled() and '30.0 秒' in page.locator('#result').inner_text())
    check('no console errors',not errors)
    browser.close()
print(f'{len(checks)} browser checks passed: '+', '.join(checks))
